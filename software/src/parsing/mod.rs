//! This module uses the rules from the [EBNF module](crate::grammar) to generate the structure of
//! The source code.

use crate::grammar::{
    is_lexing_rule,
    types::{GrammarNode, RuleMap},
};

use super::lexing::Token;

#[cfg(test)]
mod tests;

/// Represents the combination of the `grammar` rules to the `Lexer` tokens
#[derive(Debug, PartialEq, Eq)]
pub enum MatchNode {
    Token(Token),
    Rule {
        name: String,
        children: Vec<MatchNode>,
    },
}

pub fn build_syntax_tree(
    tokens: Vec<Token>,
    rules: RuleMap,
    possible_tree: Option<MatchNode>,
) -> Result<MatchNode, String> {
    // Take the given tree or the program rule as root
    let mut tree = possible_tree.unwrap_or(MatchNode::Rule {
        name: "program".to_owned(),
        children: vec![],
    });
    match &mut tree {
        MatchNode::Token(token) => return Err(format!("Tree is token: {:?}", token)),
        MatchNode::Rule { name, children } => {
            let rule = &rules[name];
            if let Some((children_nodes, matched_amount)) = tokens_match_rule(&tokens, rule, &rules)
            {
                *children = children_nodes;
            } else {
                return Err("Failed to match rule".to_owned());
            };
        }
    }
    Ok(tree)
}

/// Checks if a list of tokens generated by the lexer matches a certain rule
/// This function is similar to `matches_rule` with the difference being that it handles tokens
/// instead of raw source code
fn tokens_match_rule(
    tokens: &[Token],
    rule: &GrammarNode,
    rules: &RuleMap,
) -> Option<(Vec<MatchNode>, usize)> {
    match rule {
        GrammarNode::Sequence(list) => {
            let mut output = vec![];
            let mut first_index = 0;
            for i in list {
                if let Some((mut matched, amount)) =
                    tokens_match_rule(&tokens[first_index..], i, rules)
                {
                    output.append(&mut matched);
                    first_index += amount;
                } else {
                    return None;
                }
            }
            Some((output, first_index))
        }
        GrammarNode::Reference(reference) => {
            if is_lexing_rule(reference) {
                if tokens.is_empty() {
                    return None;
                } else if tokens[0].head == *reference {
                    // FIX: don't use clone here, maybe move it out or something
                    return Some((vec![MatchNode::Token(tokens[0].clone())], 1));
                }
            }
            if let Some(new_rule) = rules.get(reference) {
                let (matched, matched_amount) = tokens_match_rule(tokens, new_rule, rules)?;
                Some((
                    vec![MatchNode::Rule {
                        name: reference.to_owned(),
                        children: matched,
                    }],
                    matched_amount,
                ))
            } else {
                None
            }
        }
        GrammarNode::ZeroOrMore(internal_rule) => {
            let mut output = vec![];
            let mut range = 0;
            while let Some((mut v, amount)) =
                tokens_match_rule(&tokens[range..], internal_rule, rules)
            {
                output.append(&mut v);
                range += amount;
            }
            Some((output, range))
        }
        GrammarNode::Choice(to_choose) => {
            for i in to_choose {
                let result = tokens_match_rule(tokens, i, rules);
                if result.is_some() {
                    return result;
                }
            }
            None
        }
        GrammarNode::Optional(option) => {
            if let Some(match_slice) = tokens_match_rule(tokens, option, rules) {
                Some(match_slice)
            } else {
                Some((vec![], 0))
            }
        }
        GrammarNode::Grouping(group) => tokens_match_rule(tokens, group, rules),
        GrammarNode::Literal(lit) => {
            eprintln!(
                "\x1b[38;2;255;0;0mFound literal: \"\x1b[38;2;100;255;0m{lit}\x1b[38;2;255;0;0m\"  during parsing\x1b[m"
            );
            None
        }
    }
}
