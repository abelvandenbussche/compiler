//! This module uses the rules from the [EBNF module](crate::grammar) to generate the structure of
//! the source code.

use crate::grammar::{
    is_lexing_rule,
    types::{GrammarNode, RuleMap},
};

use super::lexing::Token;

/// Represents the combination of the `grammar` rules to the `Lexer` tokens
#[derive(Debug, PartialEq, Eq)]
pub enum MatchNode {
    Token(Token),
    Rule {
        name: String,
        children: Vec<MatchNode>,
    },
}

pub fn build_syntax_tree(
    tokens: Vec<Token>,
    rules: RuleMap,
    possible_tree: Option<MatchNode>,
) -> Result<MatchNode, String> {
    let mut tree = possible_tree.unwrap_or(MatchNode::Rule {
        name: "program".to_owned(),
        children: vec![],
    });
    match &mut tree {
        MatchNode::Token(token) => return Err(format!("Tree is token: {:?}", token)),
        MatchNode::Rule { name, children } => {
            let rule = &rules[name];
            if let Some(children_slice) = tokens_match_rule(&tokens, rule, &rules) {
                *children = children_slice
                    .iter()
                    .map(|token| MatchNode::Token(token.clone()))
                    .collect();
                println!("children of {name}: {:?}", children);
            } else {
                return Err("Failed to match rule".to_owned());
            };
        }
    }
    Ok(tree)
}

/// Checks if a list of tokens generated by the lexer matches a certain rule
/// This function is similar to `matches_rule` with a difference in what data it handles
fn tokens_match_rule<'a>(
    tokens: &'a [Token],
    rule: &GrammarNode,
    rules: &RuleMap,
) -> Option<&'a [Token]> {
    println!("matching: {:?}", rule);
    match rule {
        GrammarNode::Sequence(list) => {
            let mut first_index = 0;
            for i in list {
                if let Some(matched_slice) = tokens_match_rule(&tokens[first_index..], i, rules) {
                    first_index += matched_slice.len();
                } else {
                    return None;
                }
            }
            Some(&tokens[..first_index])
        }
        GrammarNode::Reference(reference) => {
            println!("reference");
            if is_lexing_rule(reference) {
                if tokens.is_empty() {
                    return None;
                } else if tokens[0].head == *reference {
                    return Some(&tokens[..1]);
                }
            }
            if let Some(new_rule) = rules.get(reference) {
                tokens_match_rule(tokens, new_rule, rules)
            } else {
                None
            }
        }
        GrammarNode::ZeroOrMore(internal_rule) => {
            let mut range = 0;
            while let Some(v) = tokens_match_rule(&tokens[range..], internal_rule, rules) {
                range += v.len()
            }
            Some(&tokens[..range])
        }
        GrammarNode::Choice(to_choose) => {
            for i in to_choose {
                let result = tokens_match_rule(tokens, i, rules);
                if result.is_some() {
                    return result;
                }
            }
            None
        }
        GrammarNode::Optional(option) => {
            if let Some(match_slice) = tokens_match_rule(tokens, option, rules) {
                Some(match_slice)
            } else {
                Some(&[])
            }
        }
        GrammarNode::Grouping(group) => tokens_match_rule(tokens, group, rules),
        GrammarNode::Literal(_) => None,
    }
}

#[cfg(test)]
mod tests {

    use crate::{
        grammar::{
            rules_to_map,
            types::{GrammarNode, Rule},
        },
        lexing::Token,
        parsing::{MatchNode, build_syntax_tree, tokens_match_rule},
    };

    #[test]
    fn tokens_matching_rule() {
        let program_rule = Rule {
            head: "program".to_owned(),
            body: Some(GrammarNode::Sequence(vec![
                GrammarNode::Reference("FOO".to_owned()),
                GrammarNode::Reference("BAR".to_owned()),
            ])),
        };
        let input_tokens = vec![
            Token {
                head: "FOO".to_owned(),
                body: "Hello".to_owned(),
            },
            Token {
                head: "BAR".to_owned(),
                body: " world!".to_owned(),
            },
            Token {
                head: "FOOBAR".to_owned(),
                body: "This should not be included".to_owned(),
            },
        ];
        let rules_map = rules_to_map(vec![program_rule]);
        assert_eq!(
            tokens_match_rule(&input_tokens, &rules_map["program"], &rules_map),
            Some(&input_tokens[..2])
        );
    }

    #[test]
    fn token_matching() {
        let rules = vec![
            Rule {
                head: "program".to_owned(),
                body: Some(GrammarNode::Sequence(vec![
                    GrammarNode::Choice(vec![
                        GrammarNode::Reference("FOO".to_owned()),
                        GrammarNode::Reference("BAR".to_owned()),
                    ]),
                    GrammarNode::ZeroOrMore(Box::new(GrammarNode::Reference("SPACE".to_owned()))),
                    GrammarNode::Optional(Box::new(GrammarNode::Reference("BAR".to_owned()))),
                ])),
            },
            Rule {
                head: "FOO".to_owned(),
                body: Some(GrammarNode::Literal("Hello".to_owned())),
            },
            Rule {
                head: "BAR".to_owned(),
                body: Some(GrammarNode::Literal("world".to_owned())),
            },
            Rule {
                head: "SPACE".to_owned(),
                body: Some(GrammarNode::Literal(" ".to_owned())),
            },
        ];
        let tokens1 = vec![
            Token {
                head: "FOO".to_owned(),
                body: "hello".to_owned(),
            },
            Token {
                head: "SPACE".to_owned(),
                body: " ".to_owned(),
            },
            Token {
                head: "BAR".to_owned(),
                body: "world".to_owned(),
            },
        ];
        let tokens2 = vec![
            Token {
                head: "BAR".to_owned(),
                body: "world".to_owned(),
            },
            Token {
                head: "SPACE".to_owned(),
                body: " ".to_owned(),
            },
            Token {
                head: "SPACE".to_owned(),
                body: " ".to_owned(),
            },
            Token {
                head: "BAR".to_owned(),
                body: "world".to_owned(),
            },
        ];
        let rules_map = rules_to_map(rules);
        let result1 = build_syntax_tree(tokens1.clone(), rules_map.clone(), None);
        let result2 = build_syntax_tree(tokens2.clone(), rules_map, None);
        assert_eq!(
            result1,
            Ok(MatchNode::Rule {
                name: "program".to_owned(),
                children: vec![
                    MatchNode::Token(tokens1[0].clone()),
                    MatchNode::Token(tokens1[1].clone()),
                    MatchNode::Token(tokens1[2].clone())
                ]
            })
        );
        assert_eq!(
            result2,
            Ok(MatchNode::Rule {
                name: "program".to_owned(),
                children: vec![
                    MatchNode::Token(tokens2[0].clone()),
                    MatchNode::Token(tokens2[1].clone()),
                    MatchNode::Token(tokens2[2].clone()),
                    MatchNode::Token(tokens2[3].clone())
                ]
            })
        );
    }
    #[test]
    fn grouping_test() {
        let rules = vec![
            Rule {
                head: "program".to_owned(),
                body: Some(GrammarNode::Choice(vec![
                    GrammarNode::Grouping(Box::new(GrammarNode::Sequence(vec![
                        GrammarNode::Reference("FOO".to_owned()),
                        GrammarNode::Reference("BAR".to_owned()),
                    ]))),
                    GrammarNode::Reference("BAR".to_owned()),
                ])),
            },
            Rule {
                head: "FOO".to_owned(),
                body: Some(GrammarNode::Literal("foo".to_owned())),
            },
            Rule {
                head: "BAR".to_owned(),
                body: Some(GrammarNode::Literal("bar".to_owned())),
            },
        ];
        let rule_map = rules_to_map(rules);
        let foo_token = Token {
            head: "FOO".to_owned(),
            body: "foo".to_owned(),
        };
        let bar_token = Token {
            head: "BAR".to_owned(),
            body: "bar".to_owned(),
        };
        // Valid
        let tokens1 = vec![foo_token.clone(), bar_token.clone()];
        // Valid
        let tokens2 = vec![bar_token.clone()];
        // Invalid
        let tokens3 = vec![foo_token.clone()];
        assert_eq!(
            build_syntax_tree(tokens1.clone(), rule_map.clone(), None),
            Ok(MatchNode::Rule {
                name: "program".to_owned(),
                children: tokens1
                    .iter()
                    .map(|i| MatchNode::Token(i.clone()))
                    .collect()
            })
        );
        assert_eq!(
            build_syntax_tree(tokens2.clone(), rule_map.clone(), None),
            Ok(MatchNode::Rule {
                name: "program".to_owned(),
                children: tokens2
                    .iter()
                    .map(|i| MatchNode::Token(i.clone()))
                    .collect()
            })
        );
        assert!(build_syntax_tree(tokens3, rule_map, None).is_err());
    }
}
