/// Represents the combination of the `grammar` rules to the `Lexer` tokens
#[derive(Debug, PartialEq, Eq)]
pub enum MatchNode {
    Token(Token),
    Rule {
        name: String,
        children: Vec<MatchNode>,
    },
}

pub fn build_syntax_tree(
    tokens: Vec<Token>,
    rules: RuleMap,
    possible_tree: Option<MatchNode>,
) -> Result<MatchNode, String> {
    let mut tree = possible_tree.unwrap_or(MatchNode::Rule {
        name: "program".to_owned(),
        children: vec![],
    });
    match &mut tree {
        MatchNode::Token(token) => return Err(format!("Tree is token: {:?}", token)),
        MatchNode::Rule { name, children } => {
            let rule = &rules[name];
            if let Some(children_slice) = tokens_match_rule(&tokens, rule, &rules) {
                *children = children_slice
                    .iter()
                    .map(|token| MatchNode::Token(token.clone()))
                    .collect();
                println!("children of {name}: {:?}", children);
            } else {
                return Err("Failed to match rule".to_owned());
            };
        }
    }
    Ok(tree)
}

/// Checks if a list of tokens generated by the lexer matches a certain rule
/// This function is similar to `matches_rule` with a difference in what data it handles
fn tokens_match_rule<'a>(
    tokens: &'a [Token],
    rule: &GrammarNode,
    rules: &RuleMap,
) -> Option<&'a [Token]> {
    println!("matching: {:?}", rule);
    match rule {
        GrammarNode::Sequence(list) => {
            let mut first_index = 0;
            for i in list {
                if let Some(matched_slice) = tokens_match_rule(&tokens[first_index..], i, rules) {
                    first_index += matched_slice.len();
                } else {
                    return None;
                }
            }
            Some(&tokens[..first_index])
        }
        GrammarNode::Reference(reference) => {
            println!("reference");
            if is_lexing_rule(reference) {
                if tokens.is_empty() {
                    return None;
                } else if tokens[0].head == *reference {
                    return Some(&tokens[..1]);
                }
            }
            if let Some(new_rule) = rules.get(reference) {
                tokens_match_rule(tokens, new_rule, rules)
            } else {
                None
            }
        }
        GrammarNode::ZeroOrMore(internal_rule) => {
            let mut range = 0;
            while let Some(v) = tokens_match_rule(&tokens[range..], internal_rule, rules) {
                range += v.len()
            }
            Some(&tokens[..range])
        }
        GrammarNode::Choice(to_choose) => {
            for i in to_choose {
                let result = tokens_match_rule(tokens, i, rules);
                if result.is_some() {
                    return result;
                }
            }
            None
        }
        GrammarNode::Optional(option) => {
            if let Some(match_slice) = tokens_match_rule(tokens, option, rules) {
                Some(match_slice)
            } else {
                Some(&[])
            }
        }
        GrammarNode::Grouping(group) => tokens_match_rule(tokens, group, rules),
        GrammarNode::Literal(_) => None,
    }
}
